library(Hmsc)
root <- normalizePath(getwd(), winslash = '/')
v4 <- file.path(root, 'DataProcessing', 'cots_sdm_v2', 'iterations', 'hmsc_corrected_v4')
m <- readRDS(file.path(v4, 'models', 'enhanced_joint_120m.rds'))
a <- readRDS(file.path(v4, 'artifacts', 'enhanced_joint_fit_data_120m.rds'))
cat('HMSC_CLASS', paste(class(m), collapse='|'), '\n')
cat('HMSC_COV', paste(m$covNames, collapse='|'), '\n')
cat('HMSC_RESP', paste(a$responses, collapse='|'), '\n')
cat('HMSC_XDATA', paste(names(a$XData), collapse='|'), '\n')
cat('HMSC_XFORMULA', paste(deparse(a$XFormula), collapse=' '), '\n')
cat('HMSC_ROWS', nrow(a$XData), 'Y', paste(dim(a$Y), collapse='x'), '\n')
b <- Hmsc::getPostEstimate(m, parName='Beta')
cat('BETA_DIM', paste(dim(b$mean), collapse='x'), '\n')
cat('BETA_ROWS', paste(rownames(b$mean), collapse='|'), '\n')
cat('BETA_COLS', paste(colnames(b$mean), collapse='|'), '\n')

d6 <- file.path(root, 'DataProcessing', 'cots_sdm_v2', 'iterations', 'density_rosetta_v6')
da <- readRDS(file.path(d6, 'artifacts', 'density_data_60m.rds'))
dm <- readRDS(file.path(d6, 'models', 'salad_native_60m.rds'))
cat('DENSITY_COLS', paste(da$design$columns, collapse='|'), '\n')
cat('DENSITY_BASE', paste(da$design$base_names, collapse='|'), '\n')
cat('DENSITY_RAW', paste(da$design$raw_names, collapse='|'), '\n')
cat('DENSITY_BETA', paste(round(dm$beta,4), collapse='|'), '\n')
